// day — дата без времени. Все даты разбора календарные: срок стоит «на 8
// июня», а не «на 8 июня 00:00 по Москве».
func day(y int, m time.Month, d int) time.Time {
	return time.Date(y, m, d, 0, 0, 0, 0, time.UTC)
}

// Seed возвращает задачу и её источники: то, с чего реестр начинает работу при
