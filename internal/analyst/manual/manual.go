// facts — журнал утверждений разбора.
//
// Факт нужен не срезу, а разговору: когда через месяц цифра изменится, по
// журналу видно, какое утверждение её держало и на каком источнике оно стояло.
// Ручной разбор ставит уверенность 1: за ним стоит человек, а не оценка модели.
func facts(o analyst.Output, now time.Time) []domain.Fact {
	pairs := passport()
	pairs = append(pairs,
		kv{"status.stage", o.Stage},
		kv{"goal.asStated", o.GoalAsStated},
		kv{"goal.clarified", o.GoalClarified},
		kv{"pmActions.nextCheck", domain.Derived(
			"20 августа — план на 12 дней у Курбанмагомеда", SourceHis,
			"до этого отчёт не отправлять: без нового плана он читается как пятый перенос; следом 26 августа — сверка по чек-листу")},
	)

	for i, v := range o.OutOfScope {
		pairs = append(pairs, kv{fmt.Sprintf("goal.outOfScope.%d", i+1), v})
	}
	for i, v := range o.Done {
		pairs = append(pairs, kv{fmt.Sprintf("status.done.%d", i+1), v})
	}
	for i, v := range o.Left {
		pairs = append(pairs, kv{fmt.Sprintf("status.left.%d", i+1), v})
	}
	for _, b := range o.Blockers {
		pairs = append(pairs, kv{"blockers." + b.ID, b.Evidence})
	}
	for _, r := range o.Risks {
		pairs = append(pairs, kv{"risks." + r.ID, r.Evidence})
	}
	for _, p := range o.Processes {
		pairs = append(pairs, kv{"processes." + string(p.Kind), p.Evidence})
	}

	out := make([]domain.Fact, 0, len(pairs))
	for i, p := range pairs {
		out = append(out, domain.Fact{
			ID:         fmt.Sprintf("f-%s-%03d", TaskID, i+1),
			TaskID:     TaskID,
			Field:      p.field,
			Value:      p.value,
			Confidence: 1,
			CreatedAt:  now,
		})
	}
	return out
}
