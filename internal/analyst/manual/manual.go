// Analyst — ручной разбор. Состояния нет: тот же вход всегда даёт тот же выход.
type Analyst struct{}

// Проверка на этапе компиляции.
var _ analyst.Analyst = (*Analyst)(nil)

// New создаёт ручного аналитика.
func New() *Analyst { return &Analyst{} }

// Name возвращает имя реализации.
func (*Analyst) Name() string { return "ручной разбор" }

// Extract возвращает разбор задачи.
//
// Источники не читаются: разбор уже сделан человеком и зафиксирован ниже.
// Задачу, которой ручной аналитик не знает, он не выдумывает — возвращает
// пустой разбор с честным объяснением. Пустой срез с пометкой «разбирать нечем»
// полезнее ошибки: PM видит загруженные источники и понимает, чего не хватает.
func (a *Analyst) Extract(ctx context.Context, in analyst.Input) (analyst.Output, error) {
	if err := ctx.Err(); err != nil {
		return analyst.Output{}, err
	}
	if in.Task.ID != TaskID {
		return unknown(in), nil
	}
	return aura(in.Now), nil
}

// unknown — разбор задачи, которой ручной аналитик не знает.
func unknown(in analyst.Input) analyst.Output {
	ask := fmt.Sprintf(
		"Ручной разбор знает только демонстрационную задачу. По задаче %q источники (%d) загружены, но не разобраны: подключите модель или разметьте поля руками.",
		in.Task.Title, len(in.Sources),
	)
	return analyst.Output{
		Stage:         domain.Missing(ask),
		GoalAsStated:  domain.Missing(ask),
		GoalClarified: domain.Missing(ask),
	}
}

