package bitrix

import (
	"strings"
	"testing"
)

// Разбор разметки — самый рискованный код пакета: это разбор строки вручную, и
// ошибка в нём не видна снаружи. Она проявится позже и не там: испорченное тело
// источника не совпадёт с цитатой, и верный факт будет отброшен как выдуманный.
// Поэтому проверяется не только то, что теги снимаются, но и то, что текст
// человека не портится.
func TestPlain(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{"пусто", "", ""},
		{"без разметки", "Смета согласована", "Смета согласована"},

		// Оформление снимается, содержимое остаётся.
		{"жирный", "[B]Смета[/B] согласована", "Смета согласована"},
		{"вложенные", "[QUOTE][B]цитата[/B][/QUOTE]", "цитата"},
		{"регистр тега", "[b]раз[/B] [I]два[/i]", "раз два"},
		{"цвет со значением", "[COLOR=#ff0000]срочно[/COLOR]", "срочно"},

		// Ссылки: остаётся то, что видит человек, адрес дописывается только
		// когда он добавляет знание.
		{"ссылка без подписи", "[URL]https://example.com[/URL]", "https://example.com"},
		{"ссылка с подписью", "[URL=https://example.com]договор[/URL]", "договор (https://example.com)"},
		{"подпись равна адресу", "[URL=https://example.com]https://example.com[/URL]", "https://example.com"},
		{"упоминание", "[USER=1]Александр[/USER], посмотри", "Александр, посмотри"},

		// Переводы строк и списки.
		{"перевод строки", "первая[BR]вторая", "первая\nвторая"},
		{"список", "[LIST][*]поднять базу[*]описать источник[/LIST]", "— поднять базу\n— описать источник"},
		{"лишние пустые строки", "а[BR][BR][BR]б", "а\n\nб"},
		{"пробелы в конце строк", "а   [BR]б  ", "а\nб"},

		// Вложения: файл приходит отдельным полем ответа, в тексте от него
		// остаётся только метка, и читателю она ничего не даёт.
		{"метка файла", "Отчёт: [DISK FILE ID=1234]отчёт.pdf[/DISK FILE ID]", "Отчёт: отчёт.pdf"},
		{"метка вложения", "[ATTACH=42]Смета на согласование", "Смета на согласование"},

		// Главное: то, что похоже на разметку, но ею не является, должно дойти
		// до среза дословно. В переписке так пишут люди.
		{"слово в скобках", "[важно] проверить смету", "[важно] проверить смету"},
		{"номер в скобках", "пункт [1] и пункт [2]", "пункт [1] и пункт [2]"},
		{"пометка о файле", "[тут был файл] перезалейте", "[тут был файл] перезалейте"},
		{"пустые скобки", "почему-то []", "почему-то []"},
		{"перевод строки внутри скобок", "[смотри\nниже]", "[смотри\nниже]"},

		// Разметка в переписке бывает битой: незакрытые и лишние теги не должны
		// съедать текст.
		{"незакрытый тег", "[B]жирный без закрытия", "жирный без закрытия"},
		{"лишнее закрытие", "текст[/B]", "текст"},
		{"закрытие не того тега", "[B]текст[/I][/B]", "текст"},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := Plain(c.in); got != c.want {
				t.Errorf("Plain(%q)\nполучено %q\nожидалось %q", c.in, got, c.want)
			}
		})
	}
}

// TestPlainLongBrackets закрепляет ограничение на длину тега: абзац,
// начинающийся с квадратной скобки, — это текст, а не разметка.
func TestPlainLongBrackets(t *testing.T) {
	in := "[" + strings.Repeat("а", 200) + "]"

	if got := Plain(in); got != in {
		t.Errorf("длинный текст в скобках изменён:\nполучено %q\nожидалось %q", got, in)
	}
}

// TestPlainKeepsWords — страховка от самой дорогой ошибки: разбор не должен
// терять слова. Проверяется на живом примере из переписки заказчика.
func TestPlainKeepsWords(t *testing.T) {
	const in = "[B]Итог:[/B] смета согласована, [I]сроки[/I] переносим на " +
		"[COLOR=red]следующую неделю[/COLOR]. Договор тут: [URL=https://b24.example.ru/doc/7]скачать[/URL]"

	got := Plain(in)

	for _, word := range []string{"Итог:", "смета", "согласована", "сроки", "переносим", "следующую", "неделю", "скачать"} {
		if !strings.Contains(got, word) {
			t.Errorf("из текста пропало слово %q: %q", word, got)
		}
	}
	if strings.ContainsAny(got, "[]") {
		t.Errorf("в тексте осталась разметка: %q", got)
	}
}
