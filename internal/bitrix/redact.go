package bitrix

import "regexp"

// Вебхук Bitrix — это URL вида https://портал/rest/1/<токен>/, и токен в нём
// равносилен паролю: с ним читаются чаты, задачи и сотрудники.
//
// Проверка на живом портале показала, что этот адрес лежит в тексте сообщений:
// портал сам присылает его в личный чат при создании вебхука («Вебхук для
// вызова rest api: …»). То есть первая же подтяжка такого чата занесла бы живой
// ключ доступа в нашу базу, а оттуда он мог бы попасть в срез и в отчёт.
//
// Поэтому текст, пришедший из Bitrix, проходит через Redact до того, как станет
// источником. Данные при этом не теряются: оригинал остаётся в Bitrix, а в
// реестре хранится то же сообщение с замазанным ключом.
var secretRe = regexp.MustCompile(`(?i)(/rest/\d+/)[a-z0-9]{10,}`)

// Redact заменяет токены вебхуков на «***» и сообщает, нашлось ли что-то.
// Второе значение нужно, чтобы это не проходило молча: подтяжка пишет в лог
// предупреждение, а не делает вид, что сообщение таким и было.
func Redact(s string) (string, bool) {
	if !secretRe.MatchString(s) {
		return s, false
	}
	return secretRe.ReplaceAllString(s, "${1}***"), true
}
