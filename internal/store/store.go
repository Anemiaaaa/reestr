// Package store описывает доступ к данным реестра.
//
// Интерфейс здесь, реализации — в подпакетах. Сервис работает только с
// интерфейсом, поэтому замена файла на SQL не заставит его переписывать: это
// как раз тот случай, когда абстракция оправдана — выбор хранилища ещё не
// сделан, а работать надо уже сегодня.
//
// Правило хранилища повторяет правило домена: источники и факты только
// добавляются. Методов Update и Delete нет намеренно, а не по недосмотру.
package store

import (
	"context"
	"errors"
	"time"

	"github.com/Anemiaaaa/reestr/internal/domain"
)

// ErrNotFound возвращается, когда записи с таким идентификатором нет.
var ErrNotFound = errors.New("не найдено")

// ErrExists возвращается при попытке создать запись с занятым
// идентификатором.
var ErrExists = errors.New("уже существует")

// Store — хранилище реестра.
type Store interface {
	// Empty сообщает, что в реестре нет ни одной задачи. Нужен на старте: пустой
	// реестр можно наполнить примером, непустой трогать нельзя.
	Empty(ctx context.Context) (bool, error)

	// CreateTask сохраняет новую задачу. Если идентификатор занят, возвращает
	// ErrExists.
	CreateTask(ctx context.Context, t domain.Task) error

	// Task возвращает задачу по идентификатору.
	Task(ctx context.Context, id string) (domain.Task, error)

	// Tasks возвращает все задачи, свежие первыми.
	Tasks(ctx context.Context) ([]domain.Task, error)

	// LinkChat закрепляет за задачей чат внешней системы. Задача должна
	// существовать, иначе ErrNotFound.
	//
	// Повторное закрепление того же чата обновляет подпись и не двигает курсор.
	// Человек может выбрать чат заново — после переименования в портале, из
	// другой формы, просто по второму разу, — и это не повод перечитывать
	// переписку с начала: сдвинь курсор назад, и весь чат приедет вторым
	// экземпляром.
	LinkChat(ctx context.Context, link domain.ChatLink) error

	// ChatLinks возвращает чаты, закреплённые за задачей, в порядке
	// закрепления.
	ChatLinks(ctx context.Context, taskID string) ([]domain.ChatLink, error)

	// AdvanceChatCursor сдвигает курсор синхронизации: lastMessageID — последнее
	// сообщение чата, уже сохранённое в реестре.
	//
	// Отдельный метод, а не поле в LinkChat, потому что это разные события с
	// разными правами. Закрепление делает человек, и подписью распоряжается он;
	// курсор двигает подтяжка, и только после того, как сообщения действительно
	// легли в хранилище. Курсор, уехавший вперёд раньше записи, — это пропущенная
	// переписка, о которой никто не узнает.
	//
	// Значение ставится как передано, без проверки на убывание: осознанный
	// перечит чата возможен, а запрет на него, спрятанный в хранилище, искали бы
	// потом долго. Если связи нет — ErrNotFound: сообщения прочитаны, а положить
	// их некуда, и это ошибка подтяжки, а не безобидный пропуск.
	AdvanceChatCursor(ctx context.Context, taskID, system, dialogID string, lastMessageID int, syncedAt time.Time) error

	// AddRawMessages переносит сообщения чата в реестр и отвечает, сколько из
	// них оказались новыми.
	//
	// Пачкой, а не по одному: подтяжка забирает у портала сотню сообщений за
	// вызов, и сто походов в базу вместо одного растянули бы её на пустом месте.
	//
	// Уже известные сообщения пропускаются молча, и это не снисходительность к
	// вызывающему, а условие работы курсора. Курсор ведёт подтяжка, портал может
	// отдать перекрывающийся кусок, и повтор здесь — обычный ход событий, а не
	// ошибка. Отличать «записали» от «уже было» нужно только для того, чтобы
	// подтяжка знала, двигать ли курсор, — для этого и счётчик.
	//
	// Сообщение без ключа оригинала отвергается ошибкой: опознать его нечем, и
	// при следующей подтяжке оно приехало бы вторым экземпляром. Отвергается вся
	// пачка, а не одна запись: наполовину записанная подтяжка оставила бы курсор
	// в положении, которому ничего не соответствует.
	AddRawMessages(ctx context.Context, msgs []domain.RawMessage) (int, error)

	// RawMessages возвращает перенесённые сообщения диалога в порядке номеров.
	//
	// Спрашивается по чату, а не по задаче: сообщение принадлежит чату, а какие
	// задачи его читают, знает ChatLink.
	//
	// Порядок тот же, что у источников: по дате события, при равных датах — по
	// порядку переноса. По номеру сообщения не сортируем: в ExternalRef он
	// строка, и «10» встало бы раньше «9».
	RawMessages(ctx context.Context, system, dialogID string) ([]domain.RawMessage, error)

	// AddSource добавляет источник. Источник без задачи допустим: сводка с
	// капитанского мостика говорит о нескольких задачах сразу, и фрагменты из
	// неё ссылаются на неё через ParentID.
	//
	// Если у источника заполнен внешний адрес и запись с таким адресом уже
	// есть, возвращает ErrExists: повторная подтяжка чата не должна заводить
	// второй экземпляр того же сообщения.
	AddSource(ctx context.Context, s domain.Source) error

	// Source возвращает источник по идентификатору.
	Source(ctx context.Context, id string) (domain.Source, error)

	// Sources возвращает источники задачи хроникой: по дате материала, а при
	// равных датах — в порядке поступления. Материал без даты идёт первым: его
	// дату ещё предстоит выяснить, и среди свежего он выглядел бы как самое
	// позднее событие.
	//
	// Общие источники, не привязанные к задаче, сюда не попадают: в задаче
	// участвует вырезанный из них фрагмент, а не сводка целиком.
	Sources(ctx context.Context, taskID string) ([]domain.Source, error)

	// SourceByExternal возвращает источник по адресу оригинала во внешней
	// системе — ключу domain.ExternalRef.Key. Пустой ключ всегда даёт
	// ErrNotFound: искать дубль не по чему.
	SourceByExternal(ctx context.Context, key string) (domain.Source, error)

	// SlicesUsing возвращает версии срезов, которые ссылаются на источник, от
	// старых к свежим. Отвечает на вопрос «на что этот материал повлиял»: без
	// него загруженный кусок переписки — запись в журнале, о судьбе которой
	// ничего не известно.
	SlicesUsing(ctx context.Context, sourceID string) ([]domain.SliceRef, error)

	// AddFacts добавляет извлечённые факты. Существующие факты не заменяются:
	// новая версия значения просто ложится сверху.
	//
	// Все задачи, упомянутые в наборе, должны существовать, иначе ErrNotFound и
	// не записано ничего: набор фактов — результат одного разбора, и половина
	// разбора в хранилище хуже, чем ни одного.
	AddFacts(ctx context.Context, facts []domain.Fact) error

	// Facts возвращает факты задачи в порядке добавления.
	Facts(ctx context.Context, taskID string) ([]domain.Fact, error)

	// PutProcess сохраняет схему процесса, заменяя прежнюю схему того же вида.
	// Схема — не факт, а его отображение, и пересобирается целиком. Задача
	// должна существовать, иначе ErrNotFound.
	PutProcess(ctx context.Context, p domain.Process) error

	// Processes возвращает схемы задачи: «как есть» и «как будет».
	Processes(ctx context.Context, taskID string) ([]domain.Process, error)

	// SaveSlice сохраняет собранный срез как очередную версию. Если версия с
	// таким номером уже есть, возвращает ErrExists: собранная версия не
	// переписывается, иначе сравнение «было → стало» потеряло бы смысл. Задача
	// должна существовать, иначе ErrNotFound.
	SaveSlice(ctx context.Context, s domain.Slice) error

	// LatestSlice возвращает последнюю собранную версию среза.
	LatestSlice(ctx context.Context, taskID string) (domain.Slice, error)

	// SliceVersion возвращает конкретную версию среза; если её нет —
	// ErrNotFound.
	//
	// Нужен сравнению «было → стало»: старая версия обязана объясняться тем
	// материалом, который был у неё на руках, и читать её нужно целиком, а не
	// пересобирать заново.
	SliceVersion(ctx context.Context, taskID string, version int) (domain.Slice, error)

	// SliceVersions перечисляет версии среза задачи, свежие первыми. У задачи
	// без единой сборки — пустой список, а не ошибка.
	SliceVersions(ctx context.Context, taskID string) ([]domain.SliceRef, error)

	// AddIncident записывает случай в журнал. Задача должна существовать, иначе
	// ErrNotFound: случай без задачи нечем проверить, а «дата, задача, что
	// произошло» — требование самой системы оплаты.
	//
	// Занятый идентификатор — ErrExists. Журнал только пополняется: запись,
	// однажды сделанная, не правится, иначе оценка перестанет объясняться тем,
	// что было зафиксировано в момент события.
	AddIncident(ctx context.Context, in domain.Incident) error

	// Incidents возвращает журнал, свежие случаи первыми. Пустой taskID означает
	// «по всем задачам».
	Incidents(ctx context.Context, taskID string) ([]domain.Incident, error)

	// NextSliceVersion возвращает номер, который получит следующая сборка.
	NextSliceVersion(ctx context.Context, taskID string) (int, error)
}
