package service

import (
	"context"
	"errors"
	"time"

	"github.com/Anemiaaaa/reestr/internal/domain"
)

// Rebuilder — ночная пересборка срезов.
//
// Существует потому, что реестр обязан быть свежим к утру без участия человека:
// PM открывает список задач и видит вчерашний день, а не вчерашнюю неделю.
//
// Считать здесь нечего — вся работа в Service.Rebuild. Задача этого типа одна:
// разбудить сборку в нужный час по нужному поясу и не сломаться, если что-то
// пойдёт не так.
type Rebuilder struct {
	svc *Service
	at  time.Time // час и минута запуска; дата в значении не используется
	loc *time.Location

	// limit — сколько задач за ночь разрешено отдать модели.
	//
	// Предел стоит не ради скорости, а ради счёта. Разбор платный, а поводов
	// для ночи, когда материал появился разом у всех задач, хватает: подтянули
	// архив переписки, завели десяток задач, портал отдал накопившееся. Без
	// предела такая ночь списала бы весь остаток, и узнали бы об этом утром.
	//
	// Ноль или меньше означает «без предела».
	limit int
}

// NewRebuilder собирает ночную пересборку на час hh:mm в поясе loc, разрешая
// отдать модели не больше limit задач за ночь.
func NewRebuilder(svc *Service, hour, minute int, loc *time.Location, limit int) *Rebuilder {
	if loc == nil {
		loc = time.UTC
	}
	return &Rebuilder{
		svc:   svc,
		at:    time.Date(2000, 1, 1, hour, minute, 0, 0, time.UTC),
		loc:   loc,
		limit: limit,
	}
}

// Run будит пересборку до отмены контекста.
//
// Отдельная горутина не создаётся: вызывающий сам решает, где этому жить, и
// видит завершение. Контекст отменяется вместе с сервером, и незавершённая
// сборка обрывается на своей задаче, а не бросается посреди записи: Rebuild
// пишет срез одним вызовом хранилища.
func (r *Rebuilder) Run(ctx context.Context) {
	for {
		wait := r.until(r.svc.now())
		r.svc.log.Info("ночная пересборка запланирована",
			"через", wait.Truncate(time.Minute).String(),
			"пояс", r.loc.String())

		timer := time.NewTimer(wait)
		select {
		case <-ctx.Done():
			timer.Stop()
			return
		case <-timer.C:
		}

		r.RunOnce(ctx)
	}
}

// until — сколько ждать до ближайшего срабатывания.
//
// Считается в поясе запуска, а не в UTC: «20:00 по Москве» обязано остаться
// восемью вечера и после перевода часов, и на сервере, живущем по Гринвичу.
func (r *Rebuilder) until(now time.Time) time.Duration {
	local := now.In(r.loc)
	next := time.Date(local.Year(), local.Month(), local.Day(),
		r.at.Hour(), r.at.Minute(), 0, 0, r.loc)
	if !next.After(local) {
		next = next.AddDate(0, 0, 1)
	}
	return next.Sub(local)
}

// RunOnce проходит реестр один раз: подтягивает переписку и пересобирает то, у
// чего появился материал.
//
// Подтяжка идёт первой и обязательно. Без неё ночь была обещанием, которого
// реестр не сдерживал: срез пересобирался из того же материала, что и вчера,
// потому что новые сообщения портала сами в реестр не приходят. Утром PM видел
// «пересобрано» и вчерашнюю картину.
//
// Порядок «сначала все подтяжки, потом разборы» выбран ради предела. Подтяжка
// у портала бесплатна, разбор моделью — нет; сделав сначала всё бесплатное, мы
// точно знаем, у скольких задач появился материал, и тратим предел на них, а не
// на первые попавшиеся по алфавиту.
//
// Ошибка на одной задаче не останавливает остальные. Ночной проход обязан
// дойти до конца: недоступный портал или отказ модели на одной задаче — не
// повод оставить без свежего среза все прочие.
func (r *Rebuilder) RunOnce(ctx context.Context) {
	started := r.svc.now()

	tasks, err := r.svc.store.Tasks(ctx)
	if err != nil {
		r.svc.log.Error("ночная пересборка: список задач", "ошибка", err)
		return
	}

	pulled := r.pullAll(ctx, tasks)

	var built, skipped, failed, over int
	for _, t := range tasks {
		// Отмена проверяется перед каждой задачей: остановка сервера не должна
		// ждать, пока модель разберёт весь реестр.
		if ctx.Err() != nil {
			r.svc.log.Info("ночная пересборка прервана",
				"собрано", built, "пропущено", skipped, "с ошибкой", failed)
			return
		}

		// Предел считается по разобранным, а не по пройденным задачам: задача
		// без нового материала модель не зовёт и счёт не тратит.
		if r.limit > 0 && built >= r.limit {
			over++
			continue
		}

		switch _, err := r.svc.Rebuild(ctx, t.ID); {
		case err == nil:
			built++
		case errors.Is(err, ErrNoChanges):
			// Пропуск неизменившегося материала — успех, а не ошибка: у
			// большинства задач за сутки не появляется ничего нового, и это
			// обычная ночь. С платной моделью это главная статья экономии.
			skipped++
		default:
			// Ошибка остаётся у своей задачи: предыдущий срез на месте, пустым
			// он не подменяется, и утром видно, какая именно задача не собралась.
			failed++
			r.svc.log.Error("ночная пересборка задачи", "задача", t.ID, "ошибка", err)
		}
	}

	if over > 0 {
		// Отдельной строкой и уровнем выше: это не обычная ночь, а упёршийся
		// предел, и человек должен узнать о нём из лога, а не из расхождения
		// между «пересобрано» и тем, что он видит на экране.
		r.svc.log.Warn("ночная пересборка упёрлась в предел разборов",
			"предел", r.limit, "не дошли до задач", over,
			"подсказка", "поднимите REESTR_NIGHTLY_LIMIT или пересоберите вручную")
	}

	r.svc.log.Info("ночная пересборка закончена",
		"задач", len(tasks), "подтянуто сообщений", pulled,
		"собрано", built, "пропущено", skipped, "с ошибкой", failed,
		"заняла", r.svc.now().Sub(started).Truncate(time.Second).String())
}

// pullAll подтягивает переписку по всем задачам и возвращает число новых
// сообщений.
//
// Отказ подтяжки не считается ошибкой ночи: у задачи может не быть чата, портал
// может быть не настроен, связь может отвалиться. Ни одно из этого не повод не
// пересобрать срезы из того материала, что уже лежит в реестре.
func (r *Rebuilder) pullAll(ctx context.Context, tasks []domain.Task) int {
	if !r.svc.PortalConfigured() {
		return 0
	}

	total := 0
	for _, t := range tasks {
		if ctx.Err() != nil {
			return total
		}
		res, err := r.svc.PullChats(ctx, t.ID)
		if err != nil {
			r.svc.log.Warn("ночная подтяжка", "задача", t.ID, "ошибка", err)
			continue
		}
		for _, p := range res {
			total += p.Added
		}
	}
	return total
}
