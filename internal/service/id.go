package service

import (
	"crypto/rand"
	"encoding/hex"
)

// newID выдаёт короткий идентификатор с приставкой вида: t-3f9a1c2b.
//
// Не UUID, потому что идентификатор попадает в адрес страницы и в лог, и его
// читают глазами. Не счётчик, потому что счётчик пришлось бы хранить и
// синхронизировать. Четырёх байт случайности хватает на реестр задач одного
// человека, а хранилище всё равно откажется создать задачу с занятым
// идентификатором.
func newID(prefix string) string {
	var b [4]byte
	if _, err := rand.Read(b[:]); err != nil {
		// rand.Read по контракту не возвращает ошибку; если вернул — среда
		// сломана настолько, что тихий запасной вариант только скроет причину.
		panic("нет источника случайности: " + err.Error())
	}
	return prefix + "-" + hex.EncodeToString(b[:])
}
