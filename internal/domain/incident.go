package domain

import (
	"strings"
	"time"
)

// KPIBlock — блок оценки из системы оплаты труда.
//
// Список закрытый и повторяет презентацию «Новая система оплаты труда»: четыре
// блока с весами 30/30/20/20. Закрытый он не для строгости, а ради правила «не
// применяем двойное наказание»: пока блоков конечное число и у случая он ровно
// один, проверить, что один случай не списан дважды, может программа. Со
// свободной строкой на этом месте проверять было бы нечего.
type KPIBlock string

const (
	KPIDeadlines  KPIBlock = "deadlines"  // сроки и качество, 30%
	KPIHours      KPIBlock = "hours"      // план полезных часов, 30%
	KPIEscalate   KPIBlock = "escalate"   // эскалация и самостоятельность, 20%
	KPIDiscipline KPIBlock = "discipline" // дисциплина и коммуникация, 20%
)

// Label возвращает подпись блока для интерфейса.
func (b KPIBlock) Label() string {
	switch b {
	case KPIDeadlines:
		return "сроки и качество"
	case KPIHours:
		return "план полезных часов"
	case KPIEscalate:
		return "эскалация и самостоятельность"
	case KPIDiscipline:
		return "дисциплина и коммуникация"
	}
	return string(b)
}

// Weight — вес блока в оценке, доля от 0 до 1.
func (b KPIBlock) Weight() float64 {
	switch b {
	case KPIDeadlines, KPIHours:
		return 0.3
	case KPIEscalate, KPIDiscipline:
		return 0.2
	}
	return 0
}

// Valid сообщает, известен ли такой блок.
func (b KPIBlock) Valid() bool { return b.Weight() > 0 }

// KPIBlocks перечисляет блоки в порядке убывания веса — в том же, в каком они
// идут в презентации.
func KPIBlocks() []KPIBlock {
	return []KPIBlock{KPIDeadlines, KPIHours, KPIEscalate, KPIDiscipline}
}

// Incident — зафиксированный случай, от которого руководитель отталкивается при
// оценке.
//
// Существует потому, что правило системы оплаты гласит: без факта нет снижения
// KPI. Оценка «75%» без записи, за что именно, — это мнение; запись с датой,
// задачей и описанием — основание, которое можно показать специалисту.
//
// Реестр здесь ничего не оценивает и не считает зарплату. Он хранит случаи и
// проверяет то, что можно проверить машиной: заполнены ли обязательные поля,
// назван ли блок, не списан ли один случай на несколько блоков. Оценку в
// процентах ставит человек — она про меру, а мера машине не видна.
type Incident struct {
	ID string `json:"id"`

	// Employee — о ком запись. Строка, а не ссылка на пользователя: учётных
	// записей в реестре пока нет, а ждать их, чтобы начать вести журнал, незачем.
	Employee string `json:"employee"`

	// TaskID — задача, в которой это случилось. Обязательна: «дата, задача, что
	// произошло» — требование самой системы оплаты, и случай без задачи нечем
	// проверить.
	TaskID string `json:"taskId"`

	// At — когда случилось. Отдельно от CreatedAt: случай могли зафиксировать
	// через неделю, а относится он к своему дню.
	At        time.Time `json:"at"`
	CreatedAt time.Time `json:"createdAt"`

	// Block — блок KPI, к которому относится случай. Ровно один: правило «не
	// применяем двойное наказание» означает, что один случай не должен
	// «съедать» несколько блоков сразу.
	Block KPIBlock `json:"block"`

	// Text — что произошло, словами руководителя.
	Text string `json:"text"`

	// External означает, что причина была вне зоны контроля специалиста:
	// задачу заблокировал клиент или внешний фактор.
	//
	// Хранится как признак, а не выражается отсутствием записи, потому что
	// презентация различает два случая: сама проблема не штрафуется, штрафуется
	// молчание о ней. Внешняя помеха, о которой сообщили вовремя, — это запись
	// в журнале, объясняющая срыв, а не повод снизить оценку.
	External bool `json:"external,omitempty"`
}

// Countable сообщает, влияет ли случай на оценку.
//
// Внешняя помеха, зафиксированная вовремя, в оценку не идёт: «оцениваем только
// то, что было в зоне контроля специалиста».
func (i Incident) Countable() bool { return !i.External }

// Zero сообщает, что запись не заполнена настолько, что хранить её нечем.
func (i Incident) Zero() bool {
	return strings.TrimSpace(i.Employee) == "" ||
		strings.TrimSpace(i.TaskID) == "" ||
		strings.TrimSpace(i.Text) == "" ||
		!i.Block.Valid()
}
