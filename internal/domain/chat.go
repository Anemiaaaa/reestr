package domain

import "time"

// ChatLink — чат внешней системы, закреплённый за задачей.
//
// Отдельная сущность, а не поле задачи, по двум причинам. У связи есть
// собственное изменяемое состояние — курсор синхронизации; на поле задачи он
// заставлял бы перезаписывать задачу при каждом новом сообщении в чате. И у
// большинства задач чата нет: пустое поле в каждой задаче описывало бы это
// отсутствие хуже, чем отсутствие записи.
//
// Про правило «только добавление» нужно сказать прямо, потому что связь его
// нарушает на первый взгляд. Правило охраняет журнал: источники, факты и срезы
// не правятся, потому что срез из них выводится, и правка задним числом
// переписала бы уже собранные версии. Курсор — не материал: он закладка в чужом
// журнале, в срез не попадает, и сослаться на него нельзя. Ближайший уже
// принятый случай — Process: схема тоже заменяется целиком, потому что она
// отображение фактов, а не факт.
type ChatLink struct {
	TaskID string `json:"taskId"`

	// System — система, которой принадлежит диалог, например SystemBitrix.
	// Входит в ключ связи по той же причине, что и в ExternalRef: идентификатор
	// диалога уникален внутри портала, а не вообще.
	System string `json:"system"`

	// DialogID — то, что внешняя система ждёт в параметре диалога. Строка, а не
	// число: у личной переписки Bitrix это «8», у группового чата — «chat12».
	DialogID string `json:"dialogId"`

	// Title — подпись чата на момент закрепления, уже без разметки и без
	// токенов доступа. Копия намеренная: в портале чат могут переименовать, а
	// реестр должен помнить то, что человек выбрал глазами.
	Title string `json:"title,omitempty"`

	// LastMessageID — последнее сообщение чата, уже попавшее в реестр. Ноль
	// означает «ни одного»; подтяжка от этого значения и продолжает.
	LastMessageID int `json:"lastMessageId,omitempty"`

	// LastSyncAt — когда чат читали в последний раз. Отдельно от курсора: поход
	// в портал мог не принести ничего нового, и это не то же самое, что не
	// ходить вовсе.
	LastSyncAt time.Time `json:"lastSyncAt,omitempty"`

	// LinkedAt — когда человек выбрал чат. Повторный выбор того же чата эту дату
	// не сдвигает: это уточнение подписи, а не новое событие.
	LinkedAt time.Time `json:"linkedAt,omitempty"`
}

// Zero сообщает, что связь не заполнена: без задачи или без диалога закреплять
// нечего.
func (l ChatLink) Zero() bool { return l.TaskID == "" || l.DialogID == "" }

// Synced сообщает, что из чата уже забрали хотя бы одно сообщение.
//
// Отдельный метод, потому что подтяжка спрашивает об этом не про время: «читали
// ли» и «когда ходили в последний раз» — разные вопросы, и отвечает на первый
// только курсор.
func (l ChatLink) Synced() bool { return l.LastMessageID > 0 }
