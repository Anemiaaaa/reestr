package domain

import "time"

// ChatLink — чат внешней системы, закреплённый за задачей.
//
// Отдельная сущность, а не поле задачи, по двум причинам. У связи есть
// собственное изменяемое состояние — курсор синхронизации; на поле задачи он
// заставлял бы перезаписывать задачу при каждом новом сообщении в чате. И у
// большинства задач чата нет: пустое поле в каждой задаче описывало бы это
// отсутствие хуже, чем отсутствие записи.
//
// Про правило «только добавление» нужно сказать прямо, потому что связь его
// нарушает на первый взгляд. Правило охраняет журнал: источники, факты и срезы
// не правятся, потому что срез из них выводится, и правка задним числом
// переписала бы уже собранные версии. Курсор — не материал: он закладка в чужом
// журнале, в срез не попадает, и сослаться на него нельзя. Ближайший уже
// принятый случай — Process: схема тоже заменяется целиком, потому что она
// отображение фактов, а не факт.
type ChatLink struct {
	TaskID string `json:"taskId"`

	// System — система, которой принадлежит диалог, например SystemBitrix.
	// Входит в ключ связи по той же причине, что и в ExternalRef: идентификатор
	// диалога уникален внутри портала, а не вообще.
	System string `json:"system"`

	// DialogID — то, что внешняя система ждёт в параметре диалога. Строка, а не
	// число: у личной переписки Bitrix это «8», у группового чата — «chat12».
	DialogID string `json:"dialogId"`

	// ExternalTaskID — задача внешней системы, чей это чат. Пусто означает, что
	// чат выбран сам по себе и задачи за ним не стоит.
	//
	// Хранится, а не выводится из диалога, по двум причинам. Связь «чат 28 →
	// задача 4» существует только в портале: по одному «chat28» вернуться к
	// задаче нечем, не сходив в Bitrix ещё раз. И она не вечная — чат от задачи
	// в портале отвязать нельзя, но портал может стать недоступен, а реестр
	// обязан помнить, откуда взялся материал, и без него.
	//
	// Не в ключе связи намеренно: ключ отвечает «какой чат читаем», а это поле —
	// «почему мы его читаем». Одна и та же задача портала не может дать два
	// разных чата, так что различать связи по нему нечего.
	ExternalTaskID string `json:"externalTaskId,omitempty"`

	// Title — подпись чата на момент закрепления, уже без разметки и без
	// токенов доступа. Копия намеренная: в портале чат могут переименовать, а
	// реестр должен помнить то, что человек выбрал глазами.
	Title string `json:"title,omitempty"`

	// Kind — что это за чат: переписка с клиентом из контакт-центра, чат задачи,
	// групповой или личный.
	//
	// Хранится, а не выводится из DialogID, потому что по нему этого не видно:
	// и чат задачи, и открытая линия выглядят одинаково — «chat28». А разница
	// существенная: в открытой линии говорит клиент, и его слова весят иначе,
	// чем обсуждение между своими. Срез обязан их различать, иначе «клиент
	// сказал, что процесс завис» и «коллега предположил, что процесс завис»
	// станут одним утверждением.
	Kind ChatKind `json:"kind,omitempty"`

	// LastMessageID — последнее сообщение чата, уже попавшее в реестр. Ноль
	// означает «ни одного»; подтяжка от этого значения и продолжает.
	LastMessageID int `json:"lastMessageId,omitempty"`

	// LastSyncAt — когда чат читали в последний раз. Отдельно от курсора: поход
	// в портал мог не принести ничего нового, и это не то же самое, что не
	// ходить вовсе.
	LastSyncAt time.Time `json:"lastSyncAt,omitempty"`

	// LinkedAt — когда человек выбрал чат. Повторный выбор того же чата эту дату
	// не сдвигает: это уточнение подписи, а не новое событие.
	LinkedAt time.Time `json:"linkedAt,omitempty"`
}

// Zero сообщает, что связь не заполнена: без задачи или без диалога закреплять
// нечего.
func (l ChatLink) Zero() bool { return l.TaskID == "" || l.DialogID == "" }

// Synced сообщает, что из чата уже забрали хотя бы одно сообщение.
//
// Отдельный метод, потому что подтяжка спрашивает об этом не про время: «читали
// ли» и «когда ходили в последний раз» — разные вопросы, и отвечает на первый
// только курсор.
func (l ChatLink) Synced() bool { return l.LastMessageID > 0 }

// ChatKind — род закреплённого чата.
//
// Список закрытый и короткий: он нужен не для полноты, а чтобы отличать
// переписку с клиентом от разговора между своими. Незнакомый род сохраняется
// как есть и показывается своим значением — портал может завести новый вид
// чата, и терять из-за этого связь незачем.
type ChatKind string

const (
	// ChatLines — открытая линия контакт-центра: тут говорит клиент.
	ChatLines ChatKind = "lines"

	// ChatTask — чат задачи портала: обсуждение работы между своими.
	ChatTask ChatKind = "task"

	// ChatGroup — обычный групповой чат, ChatPrivate — личная переписка.
	ChatGroup   ChatKind = "chat"
	ChatPrivate ChatKind = "user"
)

// Label возвращает подпись рода чата для интерфейса.
func (k ChatKind) Label() string {
	switch k {
	case ChatLines:
		return "переписка с клиентом"
	case ChatTask:
		return "чат задачи"
	case ChatGroup:
		return "групповой чат"
	case ChatPrivate:
		return "личная переписка"
	}
	return string(k)
}

// Client отвечает, говорит ли в этом чате клиент.
//
// Отдельный метод, а не сравнение с ChatLines по месту: вопрос «чьи это слова»
// задают в трёх местах — при заведении источника, в подписи чата и в срезе, — и
// написанный по месту он разошёлся бы, как только у контакт-центра появится
// второй род чатов.
func (k ChatKind) Client() bool { return k == ChatLines }
