package domain

import "time"

// RawMessage — сообщение чата, перенесённое в реестр как есть.
//
// Это журнал переписки, а не материал для среза. Разница существенная: в
// источники попадает не всё подряд, а только то, на что сослался разбор, —
// иначе список источников версии перестал бы что-либо значить. Здесь же лежит
// всё, что забрала подтяжка, включая системные сообщения портала: чтобы
// сослаться на сообщение, его надо сначала иметь, а решать за разбором, что ему
// пригодится, подтяжка не вправе.
//
// Принадлежит чату, а не задаче. Один чат может обсуждать несколько задач —
// это уже разрешено связью, — и привязка сообщения к задаче заставила бы
// хранить его по копии на каждую. Какие задачи читают этот чат, знает
// ChatLink; сообщение об этом знать не обязано.
type RawMessage struct {
	// External — адрес оригинала: система, диалог, номер сообщения. Он же
	// естественный ключ записи, поэтому пустым не бывает: сообщение без
	// оригинала — это материал, вставленный руками, а такому место в Source.
	External ExternalRef `json:"external"`

	// Author — имя автора, если портал его прислал. Пустая строка означает
	// «автор неизвестен», и это честнее, чем подставлять «Сотрудник №5».
	Author string `json:"author,omitempty"`

	// AuthorID — номер автора в системе-источнике. Ноль у системных сообщений:
	// портал их пишет ни от чьего имени.
	AuthorID int `json:"authorId,omitempty"`

	Body string `json:"body"`

	// OccurredAt — когда сообщение написано, FetchedAt — когда его перенесли.
	// Различать обязательно по той же причине, что и у источника: переписка
	// июня, перенесённая в августе, говорит о июне.
	OccurredAt time.Time `json:"occurredAt,omitempty"`
	FetchedAt  time.Time `json:"fetchedAt"`

	// Service отмечает системное сообщение портала: «задача завершена»,
	// «изменён исполнитель». Хранится, но источником не становится — цитировать
	// в срезе там нечего. Отметка нужна, чтобы отличать их без разбора текста:
	// формулировки портала меняются от версии к версии, а признак — нет.
	Service bool `json:"service,omitempty"`

	// Redacted означает, что из текста убран токен доступа. Хранится вместе с
	// сообщением, а не только пишется в лог: срез может сослаться на этот текст,
	// и читатель вправе знать, что текст не дословный.
	Redacted bool `json:"redacted,omitempty"`
}

// Key — ключ сообщения вида «система:чат:сообщение». Пустой ключ означает, что
// запись негодная: хранить сообщение, которое нельзя опознать, значит завести
// дубль при первой же повторной подтяжке.
func (m RawMessage) Key() string { return m.External.Key() }

// Usable сообщает, годится ли сообщение в источники: у него есть текст, и оно
// не системное. Отдельный метод, потому что об этом спрашивают в двух местах —
// при разборе и при показе, — и разойтись эти два ответа не должны.
func (m RawMessage) Usable() bool { return !m.Service && m.Body != "" }

// At — дата, по которой сообщение встаёт в хронологию. То же решение, что и у
// Source.At: дата события, а если её нет — дата попадания в реестр.
func (m RawMessage) At() time.Time {
	if !m.OccurredAt.IsZero() {
		return m.OccurredAt
	}
	return m.FetchedAt
}
